/**
 * The constant tables of CORE-MATH's binary64 {@code tan} and the named scalar constants that decide when its fast path may answer
 * and how far the accurate path trusts its 128-bit result, in one class so that one digest covers them (the lesson of the phase B1
 * review, Fable M1: an error bound written inline can be halved without a single mismatch on the full {@code tan.wc}, so no behavioural
 * test guards it; every such constant is a named compile-time constant here, appended to {@link #snapshot()}).
 * <p>
 * <b>Bit-exact.</b> Every value is a literal copy of the C source's, generated from the C text by {@code sed}/{@code awk}: a {@code double}
 * as the same hexadecimal floating-point literal, a 64-bit word as the same hexadecimal digits. Two checks guard the tables and the named
 * constants, both in {@code CoreMathTanTablesDigestTest}: {@code everyTableEqualsTheCText} and {@code everyNamedConstantEqualsTheCText}
 * re-read {@code tan.c} and compare every table entry and every place where the C writes one of the constants to the Java value, bit for
 * bit (they need the CORE-MATH clone, so they are skipped without it and FAIL if the full tier is requested with
 * {@code -Dcore.math.full=true}); the digest test needs nothing: it hashes a canonical rendering of {@link #snapshot()} (SHA-256) and
 * compares it with the digest committed as a test resource, so a changed bit fails on every machine.
 * <p>
 * <b>The 1/(2 pi) table is not repeated.</b> {@code tan.c}'s {@code T[i]} (20 words, "computed with computeT() from sin.sage") is
 * {@code sin.c}'s {@code _T[i+1]} for {@code i < 19}, where {@link CoreMathTables#t} already holds it, plus one word, {@code T[19]}
 * ({@code 0xfc33ef0826bd0d87}), that {@code sin.c} leaves out as unused. {@link #t(int)} serves {@code tan.c}'s index from that one definition
 * and the one extra word; the snapshot renders all 20 so the digest and the C-text comparison cover the shared words too.
 * <p>
 * <b>Layout.</b> A C {@code dint64_t} table is flattened to four words per row, {@code hi, lo, ex, sgn} (value
 * {@code (-1)^sgn * (hi/2^64 + lo/2^128) * 2^ex}); {@code double SC[256][3]} is flattened row-major. The arrays are private: they are Java
 * arrays, so a package-visible array could be written by any class in this package and every later result would change silently. The
 * accessors are what the port calls; a dint is returned as a FRESH {@link CoreMathDint} (the C passes them as {@code const} pointers and
 * never writes through them; a fresh copy cannot be written back); {@link #snapshot()} gives the tests a copy.
 */
