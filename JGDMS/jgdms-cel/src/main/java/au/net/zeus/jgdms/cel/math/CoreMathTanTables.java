    static CoreMathDint dintZero() {
        return new CoreMathDint(DINT_ZERO[0], DINT_ZERO[1], DINT_ZERO[2], DINT_ZERO[3]);
    }

    /** A fresh copy of {@code ONE}. */
    static CoreMathDint dintOne() {
        return new CoreMathDint(DINT_ONE[0], DINT_ONE[1], DINT_ONE[2], DINT_ONE[3]);
    }

    /** A fresh copy of {@code MAGIC}. */
    static CoreMathDint dintMagic() {
        return new CoreMathDint(DINT_MAGIC[0], DINT_MAGIC[1], DINT_MAGIC[2], DINT_MAGIC[3]);
    }

    private static CoreMathDint row(long[] table, int i) {
        int k = 4 * i;
        return new CoreMathDint(table[k], table[k + 1], table[k + 2], table[k + 3]);
    }

    /** {@code PSfast[i]} of {@code tan.c}, 0 &lt;= i &lt; 5. */
    static double psFast(int i) {
        return PSFAST[i];
    }

    /** {@code PCfast[i]} of {@code tan.c}, 0 &lt;= i &lt; 5. */
    static double pcFast(int i) {
        return PCFAST[i];
    }

    /** {@code SC[i][k]} of {@code tan.c}, flat index {@code 3*i + k}. */
    static double sc(int flatIndex) {
        return SC[flatIndex];
    }

    /** {@code exceptions[j][k]} of {@code tan_accurate}, flat index {@code 3*j + k}. */
    static double exceptions(int flatIndex) {
        return EXCEPTIONS[flatIndex];
    }

    private static long[] bits(double[] d) {
        long[] out = new long[d.length];
        for (int i = 0; i < d.length; i++) {
            out[i] = Double.doubleToRawLongBits(d[i]);
        }
        return out;
    }

    private static long[] one(double v) {
        return new long[] {Double.doubleToRawLongBits(v)};
    }

