    /** Builds class bytes for a class whose {@code <clinit>} invokes {@code target}. */
    private static byte[] buildClinitCallingMethod(
            String owner, String name, String descriptor,
            int invokeOpcode) {

        ClassWriter cw = new ClassWriter(ClassWriter.COMPUTE_FRAMES);
        cw.visit(Opcodes.V11,
                 Opcodes.ACC_PUBLIC | Opcodes.ACC_SUPER,
                 "au/net/zeus/jgdms/bae/test/Synthetic",
                 null, "java/lang/Object", null);

        MethodVisitor mv = cw.visitMethod(
                Opcodes.ACC_STATIC, "<clinit>", "()V", null, null);
        mv.visitCode();
        mv.visitMethodInsn(invokeOpcode, owner, name, descriptor, false);
        mv.visitInsn(Opcodes.RETURN);
        mv.visitMaxs(0, 0);
        mv.visitEnd();
        cw.visitEnd();
        return cw.toByteArray();
    }

    /**
     * Builds a class whose {@code <clinit>} calls {@code SecurityManager.checkXxx}
     * (a permission guard) and then calls the given blocking method.
     *
     * <p>The generated bytecode looks like:
     * <pre>
     *   static {
     *       new SecurityManager().checkPermission(new RuntimePermission("test"));
     *       // ...blocking call...
     *   }
     * </pre>
     *
     * <p>In the call graph both the guard and the blocking call appear as direct
     * callees of {@code <clinit>}, which is sufficient for
     * {@link ClinitBlockingVisitor} to detect {@code BLOCKING_GUARDED}.
     */
    private static byte[] buildGuardedClinitCallingMethod(
            String blockingOwner, String blockingName, String blockingDescriptor,
            int invokeOpcode) {

        ClassWriter cw = new ClassWriter(ClassWriter.COMPUTE_FRAMES);
        cw.visit(Opcodes.V11,
                 Opcodes.ACC_PUBLIC | Opcodes.ACC_SUPER,
                 "au/net/zeus/jgdms/bae/test/Synthetic",
                 null, "java/lang/Object", null);

        MethodVisitor mv = cw.visitMethod(
                Opcodes.ACC_STATIC, "<clinit>", "()V", null, null);
        mv.visitCode();

        // Emit: new SecurityManager().checkPermission(new RuntimePermission("test"))
        mv.visitTypeInsn(Opcodes.NEW, "java/lang/SecurityManager");
        mv.visitInsn(Opcodes.DUP);
        mv.visitMethodInsn(Opcodes.INVOKESPECIAL,
                "java/lang/SecurityManager", "<init>", "()V", false);
        mv.visitTypeInsn(Opcodes.NEW, "java/lang/RuntimePermission");
        mv.visitInsn(Opcodes.DUP);
        mv.visitLdcInsn("test");
        mv.visitMethodInsn(Opcodes.INVOKESPECIAL,
                "java/lang/RuntimePermission", "<init>",
                "(Ljava/lang/String;)V", false);
        mv.visitMethodInsn(Opcodes.INVOKEVIRTUAL,
                "java/lang/SecurityManager", "checkPermission",
                "(Ljava/security/Permission;)V", false);

        // Emit the blocking call
        mv.visitMethodInsn(invokeOpcode,
                blockingOwner, blockingName, blockingDescriptor, false);

        mv.visitInsn(Opcodes.RETURN);
        mv.visitMaxs(4, 0);
        mv.visitEnd();
        cw.visitEnd();
        return cw.toByteArray();
    }

    private static ClinitVerdict analyze(byte[] classBytes) throws Exception {
        java.util.Map<String, java.util.Set<String>> callGraph =
                new java.util.HashMap<>();
        java.util.Map<String, Boolean> isNativeMap = new java.util.HashMap<>();
        String[] clinitOwner = { null };
        ClinitBlockingVisitor.indexClass(classBytes, callGraph, isNativeMap, clinitOwner);
        if (clinitOwner[0] == null) {
            return ClinitVerdict.CLEAN;
        }
        return ClinitBlockingVisitor.analyzeClinitReachability(
                clinitOwner[0], callGraph, isNativeMap, 20).verdict;
    }

