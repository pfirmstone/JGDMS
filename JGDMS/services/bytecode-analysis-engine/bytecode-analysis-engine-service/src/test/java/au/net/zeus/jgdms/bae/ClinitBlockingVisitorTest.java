/**
 * Unit tests for {@link ClinitBlockingVisitor} focusing on:
 * <ul>
 *   <li>{@link ClinitVerdict#BLOCKING} — unguarded blocking paths reachable
 *       from {@code <clinit>}</li>
 *   <li>{@link ClinitVerdict#BLOCKING_GUARDED} — blocking paths preceded by a
 *       {@code SecurityManager.checkXxx()} or
 *       {@code AccessController.checkPermission()} call</li>
 *   <li>New Java API blocking sinks: {@code FileInputStream.read},
 *       {@code Selector.select}, {@code SocketChannel.read},
 *       {@code StampedLock.writeLock}, {@code CompletableFuture.join},
 *       {@code Process.waitFor}, {@code LinkedTransferQueue.take},
 *       {@code DatagramSocket.receive}</li>
 *   <li>DirtyChai-specific sinks: {@code sun.nio.ch.Poller.poll} and
 *       {@code sun.nio.ch.Poller.pollSelector}</li>
 * </ul>
 *
 * <p>Each test generates a minimal synthetic class via ASM that exhibits the
 * specific bytecode pattern under test.
 *
 * @author GitHub Copilot
 */
