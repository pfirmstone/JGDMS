/**
 * End to end through real Atomic marshal streams: a downloaded dynamic proxy of
 * service B (a {@code Proxy} that is a {@code DynamicProxyCodebaseAccessor}) is
 * written into a stream, as service A would when it holds B's proxy.
 * <ol>
 * <li>Does {@code AtomicMarshalOutputStream} inline it as a ProxySerializer
 *     (bootstrap proxy + MarshalledInstance)?
 * <li>When that stream is read with the context of the connection that delivered
 *     it (service A's {@code ServerSubject}), which server identity does
 *     {@code PreferredProxyCodebaseProvider.resolve} use?
 * </ol>
 * Result: yes to both.  (Needs the {@code MarshalDelegate} generated by the
 * jgdms-marshal-delegate-processor annotation processor, as in the Maven build.)
 */
public class PreferredProxyRelayStreamTest {

    private static final String FLAG =
            PreferredProxyCodebaseProvider.SMART_PROXY_ISOLATION_ENABLED_PROPERTY;
    private SmartProxyIsolationRouter savedRouter;
    private String savedFlag;

    @Before
    public void setUp() {
        savedRouter = PreferredProxyCodebaseProvider.getIsolationRouter();
        savedFlag = System.getProperty(FLAG);
        System.setProperty(FLAG, "true");
    }

    @After
    public void tearDown() {
        PreferredProxyCodebaseProvider.setIsolationRouter(savedRouter);
        if (savedFlag == null) System.clearProperty(FLAG);
        else System.setProperty(FLAG, savedFlag);
    }

    /** Answers the CodebaseAccessor calls locally; stands for B's BasicInvocationHandler. */
    @AtomicSerial
    public static final class ServiceBHandler implements InvocationHandler {
        public static SerialForm[] serialForm() { return new SerialForm[0]; }
        public static void serialize(PutArg arg, ServiceBHandler h) throws IOException { 
            arg.writeArgs();
        }
        public ServiceBHandler() { }
        public ServiceBHandler(GetArg arg) throws IOException { }
        public Object invoke(Object proxy, Method method, Object[] args) {
            switch (method.getName()) {
                case "getClassAnnotation": return "http://localhost/service-b.jar";
                case "setConstraints": return proxy;
                case "hashCode": return 42;
                case "equals": return args != null && args[0] == proxy;
                case "toString": return "serviceB";
                default: return null;
            }
        }
    }

    public interface ServiceBApi { }

    @Test
    public void aForeignProxyHeldByServiceAIsInlinedAndAttributedToTheDeliveringStream() throws Exception {
        Probe probe = new Probe();
        PreferredProxyCodebaseProvider.setIsolationRouter(probe);

        // Service B's proxy as the client holds it: a JERI-style dynamic proxy.
        Object bProxy = Proxy.newProxyInstance(loader(), 
                new Class<?>[]{ ServiceBApi.class, DynamicProxyCodebaseAccessor.class, 
                    RemoteMethodControl.class }, new ServiceBHandler());

        // Service A writes it (in its response).
        ByteArrayOutputStream bout = new ByteArrayOutputStream();
        ObjectOutputStream out = new AtomicMarshalOutputStream(bout, loader(), 
                new ArrayList(), false);
        out.writeObject(bProxy);
        out.flush();
        byte[] wire = bout.toByteArray();
        assertTrue("written as a ProxySerializer: bootstrap proxy + MarshalledInstance",
                new String(wire, java.nio.charset.StandardCharsets.ISO_8859_1)
                        .contains("ProxySerializer"));

        // The client reads A's response: the context is A's connection's.
        Collection ctx = new ArrayList();
        ctx.add(subject("spiffe://example/service-A"));
        ObjectInputStream in = AtomicMarshalInputStream.create(
                new ByteArrayInputStream(wire), loader(), false, loader(), ctx, false);
        Object result = in.readObject();

        assertTrue("resolve ran inside the read of A's stream", probe.invoked);
        assertEquals("service B's proxy was keyed by the stream's server, A", 
                "spiffe://example/service-A", probe.principals[0].getName());
        assertSame(probe.result, result);
    }

    private static ClassLoader loader() {
        return PreferredProxyRelayStreamTest.class.getClassLoader();
    }

    private static ServerSubject subject(final String name) {
        Set<Principal> principals = new LinkedHashSet<>();
        principals.add(new Principal() {
            public String getName() { return name; }
            public boolean equals(Object o) {
                return o instanceof Principal && name.equals(((Principal) o).getName());
            }
            public int hashCode() { return name.hashCode(); }
            public String toString() { return name; }
        });
        final Subject s = new Subject(true, principals, Collections.emptySet(), 
                Collections.emptySet());
        return () -> s;
    }

    private static final class Probe implements SmartProxyIsolationRouter {
        final Object result = new Object();
        volatile boolean invoked;
        volatile Principal[] principals;
        public Object route(Principal[] serverPrincipals, CodebaseAccessor bootstrapProxy,
                            MarshalledInstance serviceProxy, URL[] codebase, String path,
                            ClassLoader parent, ClassLoader verifier, Collection context) {
            invoked = true;
            principals = serverPrincipals;
            return result;
        }
    }
}
