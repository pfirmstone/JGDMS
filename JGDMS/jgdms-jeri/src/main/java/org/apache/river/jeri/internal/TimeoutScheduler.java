package org.apache.river.jeri.internal;

import java.security.AccessController;
import java.security.PrivilegedAction;
import java.util.Set;
import java.util.concurrent.Executor;
import java.util.concurrent.Executors;
import java.util.concurrent.ScheduledFuture;
import java.util.concurrent.ScheduledThreadPoolExecutor;
import java.util.concurrent.ThreadFactory;
import java.util.concurrent.TimeUnit;
import java.util.concurrent.atomic.AtomicLong;
import java.util.logging.Level;
import java.util.logging.Logger;
import javax.security.auth.Subject;

/**
 * The one timer that ends connections which have run out of time to start,
 * or to be acknowledged: a server's TLS handshake that has not finished, a
 * mux connection whose peer has not sent its header, a mux request whose
 * acknowledgment has not come.
 *
 * <p>One thread serves all the endpoints that use this copy of the class (it
 * is a static, so one for each class loader: a second copy of jgdms-jeri in
 * the same JVM has a thread of its own, and a bundle that is refreshed leaves
 * the thread of its old revision, with that revision's class loader, until
 * the JVM ends), so a flood of
 * connections costs queue entries and not threads, and so one task that
 * waits delays every deadline.  A task must therefore only flip some state
 * and, if there is anything to close or to notify, call {@link #handOff} to
 * have another thread do it: closing a socket can block (a socket with a
 * linger time), and so can taking the lock of a connection.
 *
 * <p>The class is public only because the callers are in three packages.
 * Its methods run on behalf of the callers' classes only: a call from any
 * other class, loaded by any loader, fails with a {@link SecurityException},
 * whether or not a security manager is installed, so downloaded or foreign
 * code cannot use the timer to run its work on, or to delay, the threads that
 * enforce the deadlines of the JVM's connections.
 *
 * <p>The threads are created when this class is initialised, in a privileged
 * action, under {@code Subject.callAs(null, ...)} and without the inheritable
 * thread locals of the thread that happens to initialise it: a thread that is
 * created lazily from a request thread keeps that thread's subject, context
 * class loader and thread locals for the life of the JVM.
 *
 * <p><b>Permissions.</b>  Under a security manager the class needs these of
 * its own protection domain, jgdms-jeri's (the code base of the jar, or of the
 * bundle revision), and of no other:
 * <ul>
 * <li>{@code java.lang.RuntimePermission "getStackWalkerWithClassReference"},
 *     for the {@link StackWalker} that finds the caller's class.  It is
 *     checked once, when the walker is obtained, in the static initialiser,
 *     not at each call;
 * <li>{@code javax.security.auth.AuthPermission "callAs"},
 *     {@code java.lang.RuntimePermission "createPlatformThread"} and
 *     {@code java.lang.RuntimePermission "setContextClassLoader"}, for the
 *     threads that are created neutral.
 * </ul>
 * Every one of these is requested inside {@link
 * AccessController#doPrivileged(PrivilegedAction)} of this class, so that
 * the check ends at jgdms-jeri's domain: the code that happens to use the
 * scheduler first, and the callers of the mux and of the TLS endpoints, need
 * hold none of them.  A policy that is generated by recording a run (polpAudit)
 * therefore records them against jgdms-jeri's code base and against no
 * application's; if the generated policy lists one of them under an
 * application's code base, the lookup is not privileged any longer.  Without
 * the first, the class fails to initialise, and every server mux start and
 * every TLS server handshake fails with it.  The test {@code
 * TimeoutSchedulerPermissionTest} runs the class under a security manager that
 * checks this list and nothing else.
 */
public final class TimeoutScheduler {

    /**
     * The classes that may use the timer: the mux, which times the start of
     * a server connection and the acknowledgment of a request, and the TLS
     * server's watchdog.  They are named, not referred to, because two are
     * not visible from here; a class of that name is the same class only if
     * this loader defined it.
     */
    private static final Set<String> CALLERS = Set.of(
        "org.apache.river.jeri.internal.mux.Mux",
        "org.apache.river.jeri.internal.mux.Session",
        "net.jini.jeri.ssl.HandshakeWatchdog");

    /** The class that may inject failures, for tests: the TLS watchdog's. */
    private static final String INJECTOR = "net.jini.jeri.ssl.HandshakeWatchdog";

    private static final StackWalker CALLER = AccessController.doPrivileged(
        (PrivilegedAction<StackWalker>) () ->
            StackWalker.getInstance(StackWalker.Option.RETAIN_CLASS_REFERENCE));

    private static final ScheduledThreadPoolExecutor TIMER = create();

    private static final AtomicLong LOST = new AtomicLong();

    private static final Executor HAND_OFF = Executors.newThreadPerTaskExecutor(
        new ThreadFactory() {
            public Thread newThread(Runnable task) {
                return AccessController.doPrivileged(
                    (PrivilegedAction<Thread>) () -> Subject.callAs(null, () -> {
                        Thread t = Thread.ofVirtual()
                            .name("connection timeout task")
                            .inheritInheritableThreadLocals(false)
                            .unstarted(task);
                        t.setContextClassLoader(
                            TimeoutScheduler.class.getClassLoader());
                        return t;
                    }));
            }
        });

    private TimeoutScheduler() { }

    private static ScheduledThreadPoolExecutor create() {
        ScheduledThreadPoolExecutor timer = new ScheduledThreadPoolExecutor(
            1, task -> AccessController.doPrivileged(
                (PrivilegedAction<Thread>) () -> Subject.callAs(null, () -> {
                    /*
                     * A platform thread, so that it is not held up when the
                     * carrier threads of the virtual threads are all busy.
                     */
                    Thread t = Thread.ofPlatform()
                        .name("connection timeout scheduler")
                        .daemon(true)
                        .inheritInheritableThreadLocals(false)
                        .unstarted(task);
                    t.setContextClassLoader(
                        TimeoutScheduler.class.getClassLoader());
                    return t;
                })));
        /* A cancelled task leaves the queue at once, not at its due time. */
        timer.setRemoveOnCancelPolicy(true);
        timer.prestartAllCoreThreads();
        return timer;
    }

    /**
     * Throws a SecurityException unless the class is one of the callers.
     */
    private static void check(Class<?> caller) {
        if (caller.getClassLoader() != TimeoutScheduler.class.getClassLoader()
            || !CALLERS.contains(caller.getName()))
        {
            throw new SecurityException(
                caller.getName() + " may not use the connection timeout "
                + "scheduler");
        }
    }

    /**
     * Runs the task after the delay, unless the returned future is cancelled
     * first.  The task must not block: it sets some state, and calls {@link
     * #handOff} for anything else.
     *
     * @throws SecurityException if the caller is not one of the classes that
     *         may use the scheduler
     */
    public static ScheduledFuture<?> schedule(Runnable task, long delay,
                                              TimeUnit unit)
    {
        check(CALLER.getCallerClass());
        Injection injection = OWN.get();
        return TIMER.schedule(
            injection == null ? task : carrying(injection, task), delay, unit);
    }

    /**
     * Runs the task on a thread of its own, which is allowed to block, so
     * that the timer thread is not held up.  If no thread can be started the
     * attempt is repeated a second later, never made on the timer thread; if
     * the repeat cannot be scheduled either, the task is lost and counted.
     *
     * @throws SecurityException if the caller is not one of the classes that
     *         may use the scheduler
     */
    public static void handOff(Runnable task) {
        check(CALLER.getCallerClass());
        run(task, null);
    }

    /**
     * Runs the task as {@link #handOff(Runnable)} does, and if no thread can
     * be started, even to try again, runs the last resort on the calling
     * thread, which may be the timer's, and counts it.  The last resort must
     * be quick and must not block, and does what is left to do when the task
     * cannot be: closing a socket abortively, for example.
     *
     * @throws SecurityException if the caller is not one of the classes that
     *         may use the scheduler
     */
    public static void handOff(Runnable task, Runnable lastResort) {
        check(CALLER.getCallerClass());
        run(task, lastResort);
    }

    private static void run(Runnable task, Runnable lastResort) {
        Injection injection = current();
        try {
            if (injection != null && injection.handOff) {
                throw new java.util.concurrent.RejectedExecutionException("injected");
            }
            HAND_OFF.execute(task);
        } catch (Throwable t) {
            // out of threads or memory: try again, off this thread
            try {
                if (injection != null && injection.retry) {
                    throw new java.util.concurrent.RejectedExecutionException("injected");
                }
                Runnable again = () -> run(task, lastResort);
                TIMER.schedule(injection == null ? again : carrying(injection, again),
                               1L, TimeUnit.SECONDS);
            } catch (Throwable ignore) {
                // shut down or out of memory: only the last resort is left
                long lost = LOST.incrementAndGet();
                try {
                    long since = LOSS_LOG.report(System.nanoTime());
                    if (since > 0L) {
                        Logger.getLogger(TimeoutScheduler.class.getName()).log(
                            Level.SEVERE, "could not hand off a task of the "
                            + "connection timeout scheduler; {0} lost since the "
                            + "last line, {1} lost so far",
                            new Object[] { since, lost });
                    }
                } catch (Throwable ignored) {
                    // out of memory: counted, nothing more can be done
                }
                if (lastResort != null) {
                    try {
                        lastResort.run();
                    } catch (Throwable ignored) {
                        // nothing more can be done
                    }
                }
            }
        }
    }

    /**
     * Returns how many tasks could not be handed off, nor the hand-off
     * repeated, since the class was initialised, and so were not run (their
     * last resort, if they had one, was).
     */
    public static long lost() {
        return LOST.get();
    }

    /**
     * For tests: the failures to inject into the hand-offs of one thread, and
     * of the tasks that thread schedules.  A thread that never calls {@link
     * #inject} has none, and the tasks that it schedules are not wrapped.
     */
    private static final class Injection {
        volatile boolean handOff;
        volatile boolean retry;
    }

    /** The injection of the calling thread, if it has asked for one. */
    private static final ThreadLocal<Injection> OWN = new ThreadLocal<>();

    /**
     * On the timer's thread, while it runs a task that a thread with an
     * injection scheduled, the injection of that thread.
     */
    private static final ThreadLocal<Injection> RUNNING = new ThreadLocal<>();

    private static Injection current() {
        Injection injection = RUNNING.get();
        return injection != null ? injection : OWN.get();
    }

    /** The task, run with the injection of the thread that scheduled it. */
    private static Runnable carrying(Injection injection, Runnable task) {
        return () -> {
            RUNNING.set(injection);
            try {
                task.run();
            } finally {
                RUNNING.remove();
            }
        };
    }

    /**
     * For tests: makes the hand-offs of the calling thread, and of the tasks
     * that it schedules from now on, fail as given, or no longer, with false
     * and false.  No other thread's hand-offs are affected, so a test cannot
     * fail a hand-off of another component that runs in the same JVM.  The
     * injection can be changed afterwards and the tasks already scheduled see
     * the change.  It is public only because the callers are in other
     * packages, and it may be called by the TLS watchdog's class only, which
     * is used by tests alone: a call from any other class, or loader, fails
     * with a {@link SecurityException}.
     *
     * @param handOff the hand-off of a task fails
     * @param retry the repeat of a failed hand-off cannot be scheduled
     * @throws SecurityException if the caller is not the class that may inject
     */
    public static void inject(boolean handOff, boolean retry) {
        Class<?> caller = CALLER.getCallerClass();
        if (caller.getClassLoader() != TimeoutScheduler.class.getClassLoader()
            || !INJECTOR.equals(caller.getName()))
        {
            throw new SecurityException(
                caller.getName() + " may not inject failures into the "
                + "connection timeout scheduler");
        }
        Injection injection = OWN.get();
        if (injection == null) {
            injection = new Injection();
            OWN.set(injection);
        }
        injection.handOff = handOff;
        injection.retry = retry;
    }

    /**
     * Counts the tasks that were lost, and says when to write a line about
     * them: the first at once, then at most one for each interval, with the
     * number lost since the last line, so that a flood of expiries while the
     * JVM is out of threads or memory writes a line, not a line for each.
     */
    static final class LossLog {
        private final long intervalNanos;
        private boolean any;
        private long lastNanos;
        private long unreported;

        LossLog(long intervalNanos) {
            this.intervalNanos = intervalNanos;
        }

        /**
         * Notes a task lost at the time, and returns the number of lost tasks
         * that a line written now is about, or 0 if no line is due.
         */
        synchronized long report(long nowNanos) {
            unreported++;
            if (any && nowNanos - lastNanos < intervalNanos) {
                return 0L;
            }
            any = true;
            lastNanos = nowNanos;
            long n = unreported;
            unreported = 0L;
            return n;
        }
    }

    /** The interval between lines about lost tasks: 30 seconds. */
    private static final LossLog LOSS_LOG = new LossLog(30_000_000_000L);

    /** Returns the number of tasks that are waiting, for tests. */
    public static int pending() {
        return TIMER.getQueue().size();
    }
}
